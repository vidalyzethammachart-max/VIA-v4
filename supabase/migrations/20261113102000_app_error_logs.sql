-- Step 3 of 3 for the super admin role: the application error log.
-- Rows are written only through public.log_app_error (signed-in users) and are readable and
-- deletable only by the super admin. No form content, tokens or response bodies are stored.

CREATE TABLE IF NOT EXISTS public.app_error_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid null,
  user_role text null,
  source text not null
    CHECK (source IN ('popup', 'window_error', 'unhandled_rejection', 'react', 'network')),
  message text not null,
  stack text null,
  page_path text null,
  user_agent text null,
  context jsonb not null default '{}'::jsonb,
  fingerprint text not null
);

CREATE INDEX IF NOT EXISTS idx_app_error_logs_created_at
  ON public.app_error_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_app_error_logs_fingerprint
  ON public.app_error_logs (fingerprint);
CREATE INDEX IF NOT EXISTS idx_app_error_logs_user_created
  ON public.app_error_logs (user_id, created_at DESC);

ALTER TABLE public.app_error_logs
  ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.app_error_logs FROM PUBLIC, anon, authenticated;
GRANT SELECT, DELETE ON TABLE public.app_error_logs TO authenticated;

DROP POLICY IF EXISTS app_error_logs_select_super_admin ON public.app_error_logs;
DROP POLICY IF EXISTS app_error_logs_delete_super_admin ON public.app_error_logs;

CREATE POLICY app_error_logs_select_super_admin
ON public.app_error_logs
FOR SELECT
TO authenticated
USING (public.is_super_admin());

CREATE POLICY app_error_logs_delete_super_admin
ON public.app_error_logs
FOR DELETE
TO authenticated
USING (public.is_super_admin());

CREATE OR REPLACE FUNCTION public.log_app_error(
  p_source text,
  p_message text,
  p_stack text,
  p_page_path text,
  p_user_agent text,
  p_context jsonb,
  p_fingerprint text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  caller_id uuid := auth.uid();
BEGIN
  -- Reporting must never break the page: every problem just drops the report.
  IF caller_id IS NULL THEN
    RETURN;
  END IF;

  IF p_source IS NULL
    OR p_source NOT IN ('popup', 'window_error', 'unhandled_rejection', 'react', 'network')
    OR p_message IS NULL
    OR btrim(p_message) = '' THEN
    RETURN;
  END IF;

  -- Flood guard: at most 60 rows per user per minute.
  IF (
    SELECT count(*)
    FROM public.app_error_logs
    WHERE user_id = caller_id
      AND created_at > now() - interval '1 minute'
  ) >= 60 THEN
    RETURN;
  END IF;

  INSERT INTO public.app_error_logs (
    user_id,
    user_role,
    source,
    message,
    stack,
    page_path,
    user_agent,
    context,
    fingerprint
  )
  VALUES (
    caller_id,
    public.current_user_role()::text,
    p_source,
    left(p_message, 2000),
    left(p_stack, 8000),
    left(p_page_path, 500),
    left(p_user_agent, 300),
    CASE
      WHEN p_context IS NULL THEN '{}'::jsonb
      WHEN length(p_context::text) > 8192 THEN jsonb_build_object('truncated', true)
      ELSE p_context
    END,
    left(COALESCE(NULLIF(btrim(p_fingerprint), ''), 'unknown'), 64)
  );
EXCEPTION
  WHEN OTHERS THEN
    NULL;
END;
$$;

REVOKE ALL
ON FUNCTION public.log_app_error(text, text, text, text, text, jsonb, text)
FROM PUBLIC, anon;

GRANT EXECUTE
ON FUNCTION public.log_app_error(text, text, text, text, text, jsonb, text)
TO authenticated;

NOTIFY pgrst, 'reload schema';
