import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

const sql = readFileSync(
  new URL("../supabase/migrations/20261113102000_app_error_logs.sql", import.meta.url),
  "utf8",
);
const rpcStart = sql.search(/create or replace function public\.log_app_error/i);
const rpc = rpcStart >= 0 ? sql.slice(rpcStart, sql.indexOf("$$;", sql.indexOf("AS $$", rpcStart)) + 3) : "";

test("the table has the spec columns and exactly the five sources", () => {
  assert.match(sql, /create table if not exists public\.app_error_logs/i);
  for (const column of [
    "id bigint generated by default as identity primary key",
    "created_at timestamptz not null default now()",
    "user_id uuid null",
    "user_role text null",
    "source text not null",
    "message text not null",
    "stack text null",
    "page_path text null",
    "user_agent text null",
    "context jsonb not null default '{}'::jsonb",
    "fingerprint text not null",
  ]) {
    assert.ok(sql.toLowerCase().includes(column), `${column} missing`);
  }
  assert.match(
    sql,
    /check \(source in \('popup', 'window_error', 'unhandled_rejection', 'react', 'network'\)\)/i,
  );
});

test("only the super admin can read or delete rows, and nobody can write directly", () => {
  assert.match(sql, /alter table public\.app_error_logs\s+enable row level security/i);
  assert.match(sql, /create policy app_error_logs_select_super_admin[\s\S]*?for select[\s\S]*?using \(public\.is_super_admin\(\)\)/i);
  assert.match(sql, /create policy app_error_logs_delete_super_admin[\s\S]*?for delete[\s\S]*?using \(public\.is_super_admin\(\)\)/i);
  assert.doesNotMatch(sql, /for\s+(insert|update|all)\b/i);
  assert.match(sql, /revoke all on table public\.app_error_logs from public, anon, authenticated/i);
  assert.match(sql, /grant select, delete on table public\.app_error_logs to authenticated/i);
});

test("log_app_error is a definer RPC that validates, truncates, flood-guards and never raises", () => {
  assert.ok(rpc, "log_app_error is missing");
  assert.match(rpc, /p_source text,\s*p_message text,\s*p_stack text,\s*p_page_path text,\s*p_user_agent text,\s*p_context jsonb,\s*p_fingerprint text/i);
  assert.match(rpc, /returns void/i);
  assert.match(rpc, /security definer/i);
  assert.match(rpc, /set search_path = public/i);
  assert.match(rpc, /auth\.uid\(\)/i);
  assert.match(rpc, /current_user_role\(\)/i);
  assert.match(rpc, /p_source not in \('popup', 'window_error', 'unhandled_rejection', 'react', 'network'\)/i);
  for (const limit of ["2000", "8000", "500", "300"]) {
    assert.match(rpc, new RegExp(`left\\([^)]*,\\s*${limit}\\)`), `limit ${limit}`);
  }
  assert.match(rpc, /length\(p_context::text\) > 8192/i);
  assert.match(rpc, /interval '1 minute'/i);
  assert.match(rpc, />= 60/);
  assert.match(rpc, /exception\s+when others then\s+null/i);
});

test("the RPC is callable by signed-in users only", () => {
  assert.match(sql, /revoke all\s+on function public\.log_app_error\([^)]*\)\s+from public, anon/i);
  assert.match(sql, /grant execute\s+on function public\.log_app_error\([^)]*\)\s+to authenticated/i);
});

test("indexes support the list page and the flood check", () => {
  assert.match(sql, /create index if not exists idx_app_error_logs_created_at\s+on public\.app_error_logs \(created_at desc\)/i);
  assert.match(sql, /create index if not exists idx_app_error_logs_fingerprint\s+on public\.app_error_logs \(fingerprint\)/i);
  assert.match(sql, /create index if not exists idx_app_error_logs_user_created\s+on public\.app_error_logs \(user_id, created_at desc\)/i);
});
